#!/usr/bin/env bash
# Tests for registry-backfill.sh — restoring the registry from transcripts that already exist.
set -uo pipefail

FILL="$(cd "$(dirname "$0")/.." && pwd)/bin/registry-backfill.sh"
PASS=0; FAIL=0
ok()   { PASS=$((PASS+1)); printf '  ok    %s\n' "$1"; }
fail() { FAIL=$((FAIL+1)); printf '  FAIL  %s\n     %s\n' "$1" "${2:-}"; }
check() { local d="$1"; shift; if "$@"; then ok "$d"; else fail "$d" "not met: $*"; fi; }

setup() {
  TMP="$(mktemp -d)"
  export HOME="$TMP/home"
  export SESSIONS_DIR="$HOME/.agent-sync/sessions"
  export SESSIONS_HOST=machine-a
  export PROJECTS_DIR="$HOME/.claude/projects"
  mkdir -p "$PROJECTS_DIR" "$SESSIONS_DIR/$SESSIONS_HOST"
}
teardown() { rm -rf "$TMP"; }
run_test() { printf '%s\n' "$1"; setup; "$2"; teardown; }

# Transcript: lines as Claude Code writes them
transcript() { # transcript <project slug> <id> <first prompt> [age] [cwd]
  local slug="$1" sid="$2" prompt="$3" age="${4:-0}" cwd="${5:-/home/me/proj}"
  mkdir -p "$PROJECTS_DIR/$slug"
  local f="$PROJECTS_DIR/$slug/$sid.jsonl"
  jq -nc --arg s "$sid" --arg c "$cwd" '{type:"summary", sessionId:$s, cwd:$c}' > "$f"
  jq -nc --arg p "$prompt" --arg c "$cwd" \
    '{type:"user", cwd:$c, message:{role:"user", content:$p}}' >> "$f"
  jq -nc '{type:"assistant", message:{role:"assistant", content:[{type:"text",text:"ok"}]}}' >> "$f"
  [ "$age" -gt 0 ] && touch -d "$age days ago" "$f"
  return 0
}

rec() { printf '%s/%s/%s.json' "$SESSIONS_DIR" "$SESSIONS_HOST" "$1"; }

# --- a session started by a slash command or by a continuation ---------------
# Claude Code puts a service block first (<local-command-caveat>,
# <command-name> etc.). If it is taken as the description, the whole list looks
# the same and search by name stops working.
t_skips_service_wrapper() {
  mkdir -p "$PROJECTS_DIR/-home-me-proj"
  local f="$PROJECTS_DIR/-home-me-proj/sess-w.jsonl"
  jq -nc --arg c /home/me/proj '{type:"user", cwd:$c, message:{role:"user",
     content:"<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>"}}' > "$f"
  jq -nc '{type:"user", message:{role:"user", content:"<command-name>/code-review</command-name>"}}' >> "$f"
  jq -nc '{type:"user", message:{role:"user", content:"fix pagination in the list"}}' >> "$f"

  "$FILL" >/dev/null 2>&1
  check "description is the real prompt, not a service block" \
    test "$(jq -r .first_prompt "$(rec sess-w)")" = "fix pagination in the list"
}

# A session with nothing but service blocks gets no description —
# but it must not disappear: without a record it cannot be found or continued.
t_service_only_transcript() {
  mkdir -p "$PROJECTS_DIR/-home-me-proj"
  local f="$PROJECTS_DIR/-home-me-proj/sess-s.jsonl"
  jq -nc --arg c /home/me/proj '{type:"user", cwd:$c, message:{role:"user",
     content:"<local-command-caveat>Caveat: ...</local-command-caveat>"}}' > "$f"
  "$FILL" >/dev/null 2>&1
  check "the record exists anyway"  test -f "$(rec sess-s)"
  check "description is not a service block" \
    test -z "$(grep -c 'local-command-caveat' "$(rec sess-s)" | grep -v '^0$')"
}

# A session started by a slash command: the description is the command name, and service
# /usage sessions (herdr runs them every 5 minutes for the limit percent) do not
# enter the registry. The old filter missed them: the first message is a caveat block.
slash_transcript() { # slash_transcript <id> <command> [real prompt]
  mkdir -p "$PROJECTS_DIR/-home-me-proj"
  local f="$PROJECTS_DIR/-home-me-proj/$1.jsonl"
  jq -nc --arg c /home/me/proj '{type:"user", cwd:$c, message:{role:"user",
     content:"<local-command-caveat>Caveat: ...</local-command-caveat>"}}' > "$f"
  jq -nc --arg n "$2" '{type:"user", message:{role:"user",
     content:("<command-name>" + $n + "</command-name>\n<command-args></command-args>")}}' >> "$f"
  [ -n "${3:-}" ] && jq -nc --arg p "$3" '{type:"user", message:{role:"user", content:$p}}' >> "$f"
  return 0
}

t_slash_command_name() {
  slash_transcript sess-cr /code-review
  "$FILL" >/dev/null 2>&1
  check "description is the command name" test "$(jq -r .first_prompt "$(rec sess-cr)")" = /code-review
}

t_skips_usage_behind_caveat() {
  slash_transcript sess-u /usage
  slash_transcript sess-c /cost
  "$FILL" >/dev/null 2>&1
  check "/usage is not in the registry" test ! -f "$(rec sess-u)"
  check "/cost is not in the registry"  test ! -f "$(rec sess-c)"
}

t_real_prompt_beats_command() {
  slash_transcript sess-m /code-review "now fix what was found"
  "$FILL" >/dev/null 2>&1
  check "the real prompt beats the command name" \
    test "$(jq -r .first_prompt "$(rec sess-m)")" = "now fix what was found"
}

# Subagent (Task) transcripts lie next to normal ones, but their ids are agent-*.
# Such a session cannot be continued — claude --resume does not know it, and in the list
# they take half of the lines.
t_skips_subagents() {
  transcript "-home-me-proj" agent-a0123 "You're working in the repo at /home/me/proj"
  transcript "-home-me-proj" sess-real  "cache fix"
  "$FILL" >/dev/null 2>&1
  check "subagent is not in the registry" test ! -f "$(rec agent-a0123)"
  check "normal session is in place"    test -f "$(rec sess-real)"
}

# A slash skill writes the SKILL.md body as the next message with isMeta — it is not a prompt.
skill_body() { # skill_body <id> <skill>
  jq -nc --arg s "$2" '{type:"user", isMeta:true, message:{role:"user",
     content:[{type:"text", text:("Base directory for this skill: /home/x/.claude/skills/" + $s)}]}}' \
    >> "$PROJECTS_DIR/-home-me-proj/$1.jsonl"
}

# herdr standing role agents: the same filter as in the session-record.sh hook.
t_skips_role_agents() {
  slash_transcript sess-rv /agent-review; skill_body sess-rv agent-review
  slash_transcript sess-cl /clear
  jq -nc '{type:"user", message:{role:"user",
     content:"<command-message>agent-qa</command-message> <command-name>/agent-qa</command-name>"}}' \
    >> "$PROJECTS_DIR/-home-me-proj/sess-cl.jsonl"
  transcript "-home-me-proj" sess-rq "[REVIEW REQUEST] PR acme/acme-api#98"
  transcript "-home-me-proj" sess-ty "you are agent-reviewer, follow the skill"
  transcript "-home-me-proj" sess-us "agent-sync is not syncing"
  slash_transcript sess-rt /retro "and now analyze [DB REQUEST]"
  "$FILL" >/dev/null 2>&1
  check "/agent-review is not in the registry"         test ! -f "$(rec sess-rv)"
  check "/agent-qa after /clear is not in the registry"         test ! -f "$(rec sess-cl)"
  check "[REVIEW REQUEST] is not in the registry"               test ! -f "$(rec sess-rq)"
  check "'you are agent-…' is not in the registry" test ! -f "$(rec sess-ty)"
  check "similar user prompt is recorded" test -f "$(rec sess-us)"
  check "REQUEST not at the start — session is recorded"   test -f "$(rec sess-rt)"
}

t_skill_body_not_description() {
  slash_transcript sess-cr /code-review; skill_body sess-cr code-review
  "$FILL" >/dev/null 2>&1
  check "description is the command name, not the skill body" \
    test "$(jq -r .first_prompt "$(rec sess-cr)")" = /code-review
}

t_custom_ignore_filter() {
  transcript "-home-me-proj" sess-x "[TMP] draft"
  transcript "-home-me-proj" sess-y "cache fix"
  SESSIONS_IGNORE_PROMPTS='^\[TMP\]' "$FILL" >/dev/null 2>&1
  check "custom filter cuts it off"  test ! -f "$(rec sess-x)"
  check "the rest is in place"    test -f "$(rec sess-y)"
}

# --- 1. a session from a transcript gets into the registry ------------------
t_basic() {
  transcript "-home-me-proj" sess-1 "cache fix"
  "$FILL" >/dev/null 2>&1
  check "record created"  test -f "$(rec sess-1)"
  check "description taken from the first prompt" \
    test "$(jq -r .first_prompt "$(rec sess-1)")" = "cache fix"
  check "directory restored from the folder name" \
    test "$(jq -r .cwd "$(rec sess-1)")" = /home/me/proj
}

# --- 2. existing records are not overwritten --------------------------------
# The registry may already hold a record with herdr data that the transcript lacks.
t_keeps_existing() {
  transcript "-home-me-proj" sess-1 "from transcript"
  jq -nc '{session_id:"sess-1", host:"machine-a", cwd:"/home/me/proj",
           started_at:"2026-09-01T10:00:00Z", last_seen:"2026-09-01T10:00:00Z",
           first_prompt:"live record", herdr:{workspace:"w9"}}' > "$(rec sess-1)"
  "$FILL" >/dev/null 2>&1
  check "record not overwritten" \
    test "$(jq -r .first_prompt "$(rec sess-1)")" = "live record"
}

# --- 3. service sessions are not pulled in -----------------------------------
t_skips_service() {
  transcript "-home-me-proj" sess-usage "/usage"
  "$FILL" >/dev/null 2>&1
  check "/usage skipped" test ! -f "$(rec sess-usage)"
}

# --- 4. old sessions outside the window are not revived ---------------------
t_skips_old() {
  transcript "-home-me-proj" sess-old "ancient task" 60
  "$FILL" >/dev/null 2>&1
  check "old session skipped" test ! -f "$(rec sess-old)"
}

# --- 5. a transcript without a user prompt is skipped -----------------------
t_skips_empty() {
  mkdir -p "$PROJECTS_DIR/-home-me-proj"
  jq -nc '{type:"summary"}' > "$PROJECTS_DIR/-home-me-proj/sess-empty.jsonl"
  "$FILL" >/dev/null 2>&1
  check "empty transcript skipped" test ! -f "$(rec sess-empty)"
}

# --- 6. the report says how many were restored -------------------------------
t_reports() {
  transcript "-home-me-a" sess-1 "first"
  transcript "-home-me-b" sess-2 "second"
  local out; out="$("$FILL" 2>&1)"
  check "number is named" grep -qE '2' <<<"$out"
}

# --- 7. a path with dashes is restored correctly ----------------------------
# The folder slug is the path with "/" replaced by "-"; reversing it breaks
# names like "web-login-redirect". The real path is in the transcript itself.
t_path_with_dashes() {
  transcript "-home-me-proj--worktrees-web-login-redirect" sess-wt "review fixes" 0 \
    "/home/me/proj/.worktrees/web-login-redirect"
  "$FILL" >/dev/null 2>&1
  check "path taken from the transcript" \
    test "$(jq -r .cwd "$(rec sess-wt)")" = "/home/me/proj/.worktrees/web-login-redirect"
}

REG="$(cd "$(dirname "$0")/.." && pwd)/bin/register-me.sh"

# --- 8. with several sessions in a project the id is required ---------------
# "The newest transcript" is the session that answered last, not the one
# running the script. With parallel work the record would go to another session.
t_requires_id_when_ambiguous() {
  transcript "-home-me-proj" sess-mine   "my work"
  transcript "-home-me-proj" sess-other  "other work"
  local rc out
  mkdir -p "$TMP/work/proj"
  out="$(cd "$TMP/work/proj" && PROJECT_DIR_OVERRIDE="$PROJECTS_DIR/-home-me-proj" "$REG" "description" 2>&1)"; rc=$?
  check "script refused"        test "$rc" -ne 0
  check "explained that an id is needed"  grep -qi 'id' <<<"$out"
  check "other record not created" test ! -f "$(rec sess-other)"
}

# --- 9. an explicit id writes exactly its own record -------------------------
t_explicit_id() {
  transcript "-home-me-proj" sess-mine  "my work"
  transcript "-home-me-proj" sess-other "other work"
  mkdir -p "$TMP/work/proj"
  (cd "$TMP/work/proj" && PROJECT_DIR_OVERRIDE="$PROJECTS_DIR/-home-me-proj" \
     CWD_OVERRIDE=/home/me/proj "$REG" --id sess-mine "fixing the registry") >/dev/null 2>&1
  check "own record created"   test -f "$(rec sess-mine)"
  check "description recorded"     test "$(jq -r .first_prompt "$(rec sess-mine)")" = "fixing the registry"
  check "other one untouched"      test ! -f "$(rec sess-other)"
}

# --- 9a. the write failed — say so ------------------------------------------
# session-record.sh is a hook: it must stay silent and always exit 0, so its exit
# code cannot show success. We check that the record was written, otherwise
# a broken registration looks successful and the user finds out by accident.
t_reports_write_failure() {
  transcript "-home-me-proj" sess-mine "my work"
  local rc out
  out="$(SESSIONS_DIR=/dev/null/nope PROJECT_DIR_OVERRIDE="$PROJECTS_DIR/-home-me-proj" \
         "$REG" --id sess-mine "probe" 2>&1)"; rc=$?
  check "non-zero exit code"    test "$rc" -ne 0
  check "does not say "recorded""       bash -c "! grep -q 'recorded' <<<'$out'"
  check "explains what went wrong"   grep -qi 'could not' <<<"$out"
}

# --- 10. when the project has one session, the id can be omitted -------------
t_single_session_ok() {
  transcript "-home-me-proj" sess-only "only one here"
  mkdir -p "$TMP/work/proj"
  (cd "$TMP/work/proj" && PROJECT_DIR_OVERRIDE="$PROJECTS_DIR/-home-me-proj" \
     CWD_OVERRIDE=/home/me/proj "$REG" "description") >/dev/null 2>&1
  check "record created without id" test -f "$(rec sess-only)"
}

# --- 11. from a worktree without transcripts, but with an explicit id --------
# The worktree directory slug is different, there are no transcripts — but the id is known.
t_worktree_with_id() {
  mkdir -p "$TMP/work/wt"
  (cd "$TMP/work/wt" && CWD_OVERRIDE=/home/me/proj/.worktrees/web \
     "$REG" --id sess-wt "worktree fixes") >/dev/null 2>&1
  check "record created"  test -f "$(rec sess-wt)"
  check "directory is right"  test "$(jq -r .cwd "$(rec sess-wt)")" = "/home/me/proj/.worktrees/web"
}

run_test "an id is needed when there are many sessions"       t_requires_id_when_ambiguous
run_test "an explicit id writes its own record"         t_explicit_id
run_test "a failed write is not reported as success" t_reports_write_failure
run_test "one session — no id needed"          t_single_session_ok
run_test "worktree with an explicit id"                t_worktree_with_id
run_test "a path with dashes is not distorted"      t_path_with_dashes
run_test "a session from a transcript is in the registry"    t_basic
run_test "existing records are not touched"     t_keeps_existing
run_test "service sessions are skipped"        t_skips_service
run_test "old sessions are not revived"               t_skips_old
run_test "an empty transcript is skipped"       t_skips_empty
run_test "the report gives the count"                 t_reports
run_test "a service wrapper does not go into the description" t_skips_service_wrapper
run_test "a transcript of only service blocks"  t_service_only_transcript
run_test "a slash command becomes the description"    t_slash_command_name
run_test "/usage behind a caveat block is cut off"    t_skips_usage_behind_caveat
run_test "the real prompt beats the command"       t_real_prompt_beats_command
run_test "subagent transcripts are skipped"    t_skips_subagents
run_test "role standing agents are skipped"   t_skips_role_agents
run_test "a skill body does not go into the description"       t_skill_body_not_description
run_test "custom SESSIONS_IGNORE_PROMPTS filter"  t_custom_ignore_filter

printf '\ntotal: %d ok, %d FAIL\n' "$PASS" "$FAIL"
[ "$FAIL" -eq 0 ]
